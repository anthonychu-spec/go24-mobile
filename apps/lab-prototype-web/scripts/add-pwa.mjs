// Turns the static prototype in site/ into an installable PWA. Safe to run again:
// it rewrites the manifest and service worker, and replaces the tags between the
// <!-- pwa --> markers in every page.
//   node scripts/add-pwa.mjs site
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const site = path.resolve(process.argv[2] || 'site');
const THEME = '#131313';      // app background (Ink), used for the status bar
const BACKGROUND = '#131313'; // splash background

const manifest = {
  id: './',
  name: 'THE LAB by ONYX',
  short_name: 'THE LAB',
  description: 'THE LAB by ONYX member app prototype. Sample data only.',
  start_url: 'index.html?app=1',
  scope: './',
  display: 'standalone',
  orientation: 'portrait',
  background_color: BACKGROUND,
  theme_color: THEME,
  icons: [
    { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};
fs.writeFileSync(path.join(site, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2) + '\n');

fs.writeFileSync(path.join(site, 'pwa.js'), `// Registers the offline cache (sw.js). The app works the same without it.
if ('serviceWorker' in navigator) {
  window.addEventListener('load', function () {
    navigator.serviceWorker.register('sw.js').catch(function () {});
  });
}
`);

const tags = `<!-- pwa -->
<link rel="manifest" href="manifest.webmanifest" crossorigin="use-credentials">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="THE LAB">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="icon" type="image/png" sizes="32x32" href="icons/favicon-32.png">
<script src="pwa.js" defer></script>
<!-- /pwa -->`;

const pages = fs.readdirSync(site).filter((f) => f.endsWith('.html'));
for (const p of pages) {
  const file = path.join(site, p);
  let html = fs.readFileSync(file, 'utf8').replace(/\n?<!-- pwa -->[\s\S]*?<!-- \/pwa -->\n?/, '');
  if (!html.includes('</head>')) throw new Error(`No </head> in ${p}`);
  html = html.replace('</head>', `\n${tags}\n</head>`);
  fs.writeFileSync(file, html);
}

// Precache every file; the cache name changes whenever any file changes.
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full);
    else files.push(path.relative(site, full).split(path.sep).join('/'));
  }
})(site);
// Host config files (e.g. Cloudflare/Netlify _headers) are not served, so never precache them.
const precache = files.filter((f) => f !== 'sw.js' && !path.basename(f).startsWith('_')).sort();
// Bump SW_REV when the worker logic below changes, so installed copies replace their cache.
const SW_REV = '1';
const hash = crypto.createHash('sha1').update('sw-rev-' + SW_REV);
for (const f of precache) hash.update(f).update(fs.readFileSync(path.join(site, f)));
const version = hash.digest('hex').slice(0, 12);

fs.writeFileSync(path.join(site, 'sw.js'), `// Offline cache for the THE LAB prototype. Generated by scripts/add-pwa.mjs.
const CACHE = 'thelab-${version}';
const FILES = ${JSON.stringify(['./', ...precache], null, 0)};

// Some hosts redirect /page.html to /page (Cloudflare Pages does). A cached redirect can't be
// served to a page navigation, so store the final response as a plain copy under the .html name.
const plain = (res) => (res.redirected
  ? res.blob().then((body) => new Response(body, { status: res.status, statusText: res.statusText, headers: res.headers }))
  : res);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((c) => Promise.all(FILES.map((f) => fetch(f, { cache: 'reload' }).then((res) => {
        if (!res.ok) throw new Error(f + ' ' + res.status);
        return Promise.resolve(plain(res)).then((copy) => c.put(f, copy));
      }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('thelab-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Cache first. Pages opened with ?app=1 match the cached page, and a page reached at its
// short address (/mobile-preview after a host redirect) matches the cached .html file.
self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  const nav = req.mode === 'navigate';
  event.respondWith(
    caches.match(req, { ignoreSearch: nav })
      .then((hit) => hit || (nav && !url.pathname.endsWith('/') && !url.pathname.endsWith('.html') ? caches.match(url.pathname + '.html', { ignoreSearch: true }) : undefined))
      .then((hit) => hit || fetch(req)),
  );
});
`);

console.log(`PWA added: ${pages.length} pages tagged, ${precache.length + 1} files precached, cache thelab-${version}`);
